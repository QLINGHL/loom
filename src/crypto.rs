//! Hand-rolled SHA-256 (FIPS 180-4) and HMAC-SHA256 (RFC 2104).
//!
//! The crate has zero external dependencies by design, so the two primitives
//! the capability system needs — a collision-resistant hash and a keyed MAC
//! for capability tokens — are implemented here directly from the specs and
//! verified against published known-answer vectors in the tests below.

